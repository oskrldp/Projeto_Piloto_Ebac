# DEFININDO UMA FUNÇÃO DE DESCONTO EM PORCENTAGEM
# "def" SE TORNA O "return"

def calcular_desconto(valor_original, desconto_porcento):
  desconto = valor_original * (desconto_porcento / 100)
  valor_final = valor_original - desconto
  return valor_final

# USAR A FUNÇÃO

