# LISTA DE DE DIAS RESTANTES DE ASSINATURA GRATUITA COM LOOL "for" (repete, siga a sequencia, mostra o tudo oq a ele foi atribuido)
# LISTAS DE NUMEROS SEMPRE VÃO DENTRO DE CORCHETES []
# NÃO ESQUEÇA DOS :
# BASICAMENTE O "for" PEGA A LISTA E FAZ UMA REGRA COM ELA APRESENTANDO ESSA LISTA PARA NÓS +- ISSO
# VAI PEGAR SOMENTE OS NUEMROS QUE ESTÇAO NA LISTA

dias_restantes = [1, 0, 5, 3, 12]

# Se os dias restantes chegarem a 0, mostrar ALERTA! Assinatura Vencida!
# Se tamben chegarem a 5, mostrar ATENÇÂO! Faltam 5 dias para sua assinatura acabar
# Se não for nenhum deles, mostrar Assinatura ativa!

for dias in dias_restantes:
  if dias == 0:
    print("ALERTA! Assinatura Vencida! Renovar")

  elif dias <= 5:
    print(f"ATENÇÂO! Faltam {dias} dias para sua assinatura acabar")

  else:
    print(f"Assinatura ativa! Faltam {dias} dias para acabar")

# CRIANDO CONTADOR COM LOOP "while"
# O "while" FAZ A SOMATORIA OU O QUE TEM QUE FAZER SOZINHO ATE CHEGAR O MANDATO DE STOP ( mostra mais do que foi atribuido ate o chegar ao atribuido)
# EXEMPLO: ME MOSTROU TODOS OS NUMEROS DO 0 AO 6
# ELE SOMA 1 OU OUTRO NUMETO MAIS O OBJETO NESTE CASO "CONTAS" E VAI INDO E MOSTRANDO ATÉ CHEGAR AO VALOR ATRIBUIDO, NESTE CASO 6, PODENDO DEIXAR PARA IR ATE O 6 OU ANTES DO 6 COM < e <=

